def write_category(filename):
    original = ORIGINALS[filename]
    builder = BUILDERS[filename]
    all_new = builder()
    result = original[:]
    seen = {item["text"] for item in result}
    start_id = len(original) + 1
    added = 0
    for text, tags in all_new:
        if text in seen:
            continue
        seen.add(text)
        result.append({"id": start_id + added, "text": text, "tags": tags})
        added += 1
        if added >= TARGET_ADD:
            break
    if added < TARGET_ADD:
        raise RuntimeError(f"{filename} 去重后不足 {TARGET_ADD} 条，仅 {added} 条")
    path = ROOT / filename
    with open(path, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent="\t")
        f.write("\n")
    print(f"{filename}: {len(result)} 条")


