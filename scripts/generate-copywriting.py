def unique_pool(items):
    seen = set()
    out = []
    for item in items:
        t = item.strip()
        if t and t not in seen:
            seen.add(t)
            out.append(t)
    return out


def take(pool, n, used):
    out = []
    for t in pool:
        if len(out) >= n:
            break
        if t not in used:
            used.add(t)
            out.append(t)
    if len(out) < n:
        raise RuntimeError(f"pool 不足，还差 {n - len(out)} 条")
    return out


